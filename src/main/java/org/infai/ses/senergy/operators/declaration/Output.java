package org.infai.ses.senergy.operators.declaration;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Declares an output of the operator. Goes on a {@code static final String} constant
 * of the operator class; the constant is the output's name, e.g.
 * {@code message.output(RESULT, value)}.
 */
@Documented
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.FIELD)
public @interface Output {
    Type type();
}
